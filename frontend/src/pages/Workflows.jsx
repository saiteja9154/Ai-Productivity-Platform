import React, { useState, useEffect, useCallback } from 'react';
import { Link } from 'react-router-dom';
import { Card, CardHeader, CardTitle, CardDescription, CardContent } from '../components/ui/Card';
import { Button } from '../components/ui/Button';
import { Badge } from '../components/ui/Badge';
import {
  getWorkflows,
  createWorkflow,
  updateWorkflow,
  deleteWorkflow,
  activateWorkflow,
  deactivateWorkflow,
  runWorkflow,
  getWorkflowExecutions
} from '../services/api';
import {
  GitFork,
  ArrowLeft,
  RefreshCw,
  AlertCircle,
  Plus,
  Play,
  CheckCircle2,
  XCircle,
  Clock,
  History,
  Trash2,
  Edit,
  Power,
  Search,
  Sparkles,
  Layers,
  ArrowRight,
  Settings2,
  FileText,
  CheckSquare
} from 'lucide-react';

const TRIGGER_LABELS = {
  manual: { label: 'Manual Trigger', color: 'bg-purple-500/15 text-purple-400 border-purple-500/30' },
  task_created: { label: 'On Task Created', color: 'bg-blue-500/15 text-blue-400 border-blue-500/30' },
  task_completed: { label: 'On Task Completed', color: 'bg-emerald-500/15 text-emerald-400 border-emerald-500/30' },
  document_uploaded: { label: 'On Doc Uploaded', color: 'bg-amber-500/15 text-amber-400 border-amber-500/30' },
  scheduled: { label: 'Scheduled Timer', color: 'bg-indigo-500/15 text-indigo-400 border-indigo-500/30' }
};

const STEP_TYPE_OPTIONS = [
  { value: 'create_task', label: 'Create Task', icon: Plus, desc: 'Creates a new task in MongoDB' },
  { value: 'assign_task', label: 'Assign Task', icon: CheckSquare, desc: 'Assigns task to a specified user' },
  { value: 'update_task_status', label: 'Update Task Status', icon: ArrowRight, desc: 'Moves task (todo / in-progress / completed)' },
  { value: 'update_task_details', label: 'Update Task Details', icon: Settings2, desc: 'Updates title, description or priority' },
  { value: 'add_comment', label: 'Log Activity Entry', icon: FileText, desc: 'Appends audit log or activity note' },
  { value: 'generate_text', label: 'Local Rule-Based Text', icon: Sparkles, desc: 'Formats deterministic status message' },
  { value: 'extract_tasks', label: 'Extract Tasks from Text', icon: Layers, desc: 'Parses action items deterministically' },
  { value: 'complete_workflow', label: 'Complete Execution', icon: CheckCircle2, desc: 'Explicitly completes workflow' }
];

export function Workflows() {
  const [workflows, setWorkflows] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);
  const [searchQuery, setSearchQuery] = useState('');
  const [statusFilter, setStatusFilter] = useState('all');

  // Builder Modal State
  const [isBuilderOpen, setIsBuilderOpen] = useState(false);
  const [editingWorkflow, setEditingWorkflow] = useState(null);
  const [builderForm, setBuilderForm] = useState({
    name: '',
    description: '',
    status: 'active',
    trigger: {
      type: 'manual',
      config: {}
    },
    steps: []
  });
  const [savingWorkflow, setSavingWorkflow] = useState(false);
  const [builderError, setBuilderError] = useState(null);

  // Execution History Modal State
  const [historyModal, setHistoryModal] = useState({
    isOpen: false,
    workflow: null,
    executions: [],
    loading: false,
    error: null
  });

  // Action status message
  const [actionFeedback, setActionFeedback] = useState(null);

  const fetchWorkflowList = useCallback(async () => {
    setLoading(true);
    setError(null);
    try {
      const response = await getWorkflows();
      setWorkflows(response.data || []);
    } catch (err) {
      setError(err.message || 'Failed to fetch workflows from database');
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    fetchWorkflowList();
  }, [fetchWorkflowList]);

  const showFeedback = (message, type = 'success') => {
    setActionFeedback({ message, type });
    setTimeout(() => setActionFeedback(null), 4000);
  };

  // Open Builder for Create
  const handleOpenCreate = () => {
    setEditingWorkflow(null);
    setBuilderForm({
      name: '',
      description: '',
      status: 'active',
      trigger: {
        type: 'manual',
        config: {}
      },
      steps: [
        {
          stepOrder: 1,
          stepName: 'Create Automated Follow-up Task',
          stepType: 'create_task',
          onFailure: 'stop',
          config: {
            title: 'Automated follow-up from workflow',
            description: 'Task auto-generated by Phase 6 execution engine.',
            priority: 'medium'
          }
        }
      ]
    });
    setBuilderError(null);
    setIsBuilderOpen(true);
  };

  // Open Builder for Edit
  const handleOpenEdit = (wf) => {
    setEditingWorkflow(wf);
    setBuilderForm({
      name: wf.name || '',
      description: wf.description || '',
      status: wf.status || 'active',
      trigger: wf.trigger || { type: 'manual', config: {} },
      steps: (wf.steps && wf.steps.length > 0) ? wf.steps.map((s, idx) => ({
        stepOrder: s.stepOrder || idx + 1,
        stepName: s.stepName || `Step ${idx + 1}`,
        stepType: s.stepType || 'create_task',
        onFailure: s.onFailure || 'stop',
        config: s.config || {}
      })) : []
    });
    setBuilderError(null);
    setIsBuilderOpen(true);
  };

  // Add Step in Builder
  const handleAddStep = () => {
    setBuilderForm(prev => ({
      ...prev,
      steps: [
        ...prev.steps,
        {
          stepOrder: prev.steps.length + 1,
          stepName: `Step ${prev.steps.length + 1}`,
          stepType: 'create_task',
          onFailure: 'stop',
          config: {
            title: 'Automated Task',
            priority: 'medium'
          }
        }
      ]
    }));
  };

  // Remove Step in Builder
  const handleRemoveStep = (index) => {
    setBuilderForm(prev => {
      const updated = prev.steps.filter((_, i) => i !== index).map((s, i) => ({
        ...s,
        stepOrder: i + 1
      }));
      return { ...prev, steps: updated };
    });
  };

  // Update Step Field
  const handleUpdateStep = (index, field, value) => {
    setBuilderForm(prev => {
      const updated = [...prev.steps];
      updated[index] = { ...updated[index], [field]: value };
      return { ...prev, steps: updated };
    });
  };

  // Update Step Config Subfield
  const handleUpdateStepConfig = (index, subfield, value) => {
    setBuilderForm(prev => {
      const updated = [...prev.steps];
      updated[index] = {
        ...updated[index],
        config: {
          ...(updated[index].config || {}),
          [subfield]: value
        }
      };
      return { ...prev, steps: updated };
    });
  };

  // Save Workflow (Create or Update)
  const handleSaveWorkflow = async (e) => {
    e.preventDefault();
    if (!builderForm.name.trim()) {
      setBuilderError('Workflow name is required');
      return;
    }

    setSavingWorkflow(true);
    setBuilderError(null);

    try {
      if (editingWorkflow) {
        await updateWorkflow(editingWorkflow._id, builderForm);
        showFeedback(`Workflow "${builderForm.name}" updated successfully!`);
      } else {
        await createWorkflow(builderForm);
        showFeedback(`Workflow "${builderForm.name}" created successfully!`);
      }
      setIsBuilderOpen(false);
      await fetchWorkflowList();
    } catch (err) {
      setBuilderError(err.message || 'Failed to save workflow');
    } finally {
      setSavingWorkflow(false);
    }
  };

  // Delete Workflow
  const handleDeleteWorkflow = async (id, name) => {
    if (!window.confirm(`Are you sure you want to delete workflow "${name}"?`)) return;
    try {
      await deleteWorkflow(id);
      showFeedback(`Workflow "${name}" deleted successfully.`);
      await fetchWorkflowList();
    } catch (err) {
      showFeedback(err.message || 'Failed to delete workflow', 'error');
    }
  };

  // Activate / Deactivate Toggle
  const handleToggleActive = async (wf) => {
    try {
      if (wf.status === 'active') {
        await deactivateWorkflow(wf._id);
        showFeedback(`Workflow "${wf.name}" deactivated.`);
      } else {
        await activateWorkflow(wf._id);
        showFeedback(`Workflow "${wf.name}" activated.`);
      }
      await fetchWorkflowList();
    } catch (err) {
      showFeedback(err.message || 'Failed to toggle status', 'error');
    }
  };

  // Run Workflow Immediately
  const handleRunWorkflow = async (wf) => {
    try {
      showFeedback(`Running workflow "${wf.name}"...`, 'info');
      const res = await runWorkflow(wf._id);
      showFeedback(`Execution completed with status: ${res.data?.status || 'success'}`);
      await fetchWorkflowList();
      // Open execution details
      handleOpenHistory(wf);
    } catch (err) {
      showFeedback(err.message || 'Workflow execution failed', 'error');
    }
  };

  // Open Execution History
  const handleOpenHistory = async (wf) => {
    setHistoryModal({
      isOpen: true,
      workflow: wf,
      executions: [],
      loading: true,
      error: null
    });

    try {
      const res = await getWorkflowExecutions(wf._id);
      setHistoryModal(prev => ({
        ...prev,
        executions: res.data || [],
        loading: false
      }));
    } catch (err) {
      setHistoryModal(prev => ({
        ...prev,
        loading: false,
        error: err.message || 'Failed to load execution history'
      }));
    }
  };

  // Filtered workflows
  const filteredWorkflows = workflows.filter(wf => {
    const matchesQuery = wf.name?.toLowerCase().includes(searchQuery.toLowerCase()) ||
                         wf.description?.toLowerCase().includes(searchQuery.toLowerCase());
    const matchesStatus = statusFilter === 'all' || wf.status === statusFilter;
    return matchesQuery && matchesStatus;
  });

  return (
    <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-10 w-full relative z-10">
      {/* Background glow effects */}
      <div className="fixed inset-0 pointer-events-none overflow-hidden">
        <div className="absolute top-20 right-1/4 w-[500px] h-[300px] bg-purple-600/10 blur-[120px] rounded-full" />
        <div className="absolute top-1/2 left-10 w-[400px] h-[300px] bg-blue-600/10 blur-[120px] rounded-full" />
      </div>

      {/* Header Bar */}
      <div className="mb-8 flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4">
        <div className="flex items-center space-x-3">
          <Link to="/dashboard">
            <Button variant="ghost" size="sm" className="text-slate-400 hover:text-white">
              <ArrowLeft className="h-4 w-4 mr-1" />
              Dashboard
            </Button>
          </Link>
          <div className="h-4 w-px bg-slate-800" />
          <div className="flex items-center space-x-2">
            <div className="h-8 w-8 rounded-lg bg-purple-500/15 text-purple-400 flex items-center justify-center">
              <GitFork className="h-4 w-4" />
            </div>
            <div>
              <h1 className="text-2xl font-bold text-white tracking-tight">Workflow Automation</h1>
              <p className="text-xs text-slate-400">Deterministic triggers, ordered execution engine, and execution history</p>
            </div>
          </div>
        </div>

        <div className="flex items-center space-x-3">
          <Button
            onClick={handleOpenCreate}
            size="sm"
            className="bg-purple-600 hover:bg-purple-500 text-white shadow-lg shadow-purple-600/20 text-xs font-semibold px-4"
          >
            <Plus className="h-4 w-4 mr-1.5" />
            Create Workflow
          </Button>
          <Button
            variant="outline"
            size="sm"
            onClick={fetchWorkflowList}
            disabled={loading}
            className="border-slate-800 bg-slate-900/60 hover:bg-slate-800 text-slate-300 text-xs"
          >
            <RefreshCw className={`h-3.5 w-3.5 mr-1.5 ${loading ? 'animate-spin text-purple-400' : ''}`} />
            Refresh
          </Button>
        </div>
      </div>

      {/* Action Feedback Banner */}
      {actionFeedback && (
        <div className={`mb-6 p-4 rounded-xl border flex items-center justify-between text-xs font-medium animate-fadeIn ${
          actionFeedback.type === 'error' ? 'bg-rose-950/40 border-rose-800 text-rose-200' :
          actionFeedback.type === 'info' ? 'bg-blue-950/40 border-blue-800 text-blue-200' :
          'bg-emerald-950/40 border-emerald-800 text-emerald-200'
        }`}>
          <div className="flex items-center space-x-2">
            {actionFeedback.type === 'error' ? <XCircle className="h-4 w-4 text-rose-400" /> : <CheckCircle2 className="h-4 w-4 text-emerald-400" />}
            <span>{actionFeedback.message}</span>
          </div>
          <button onClick={() => setActionFeedback(null)} className="text-slate-400 hover:text-white">✕</button>
        </div>
      )}

      {/* Search & Filter Controls */}
      <div className="mb-6 grid grid-cols-1 sm:grid-cols-3 gap-3">
        <div className="sm:col-span-2 relative">
          <Search className="absolute left-3 top-2.5 h-4 w-4 text-slate-500" />
          <input
            type="text"
            placeholder="Search workflows by title or description..."
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            className="w-full pl-9 pr-4 py-2 bg-slate-900/60 border border-slate-800 rounded-xl text-xs text-white placeholder-slate-500 focus:outline-none focus:border-purple-500"
          />
        </div>
        <div>
          <select
            value={statusFilter}
            onChange={(e) => setStatusFilter(e.target.value)}
            className="w-full px-3 py-2 bg-slate-900/60 border border-slate-800 rounded-xl text-xs text-slate-200 focus:outline-none focus:border-purple-500"
          >
            <option value="all">All Statuses</option>
            <option value="active">Active Workflows</option>
            <option value="draft">Draft Workflows</option>
            <option value="paused">Paused Workflows</option>
            <option value="completed">Completed Workflows</option>
          </select>
        </div>
      </div>

      {/* Error State */}
      {error && (
        <Card className="bg-rose-950/20 border-rose-800/40 p-6 mb-8 text-center space-y-3">
          <AlertCircle className="h-8 w-8 text-rose-400 mx-auto" />
          <h3 className="text-base font-semibold text-rose-200">Unable to Fetch Workflows</h3>
          <p className="text-xs text-rose-300/80 max-w-md mx-auto">{error}</p>
          <Button size="sm" variant="outline" onClick={fetchWorkflowList} className="border-rose-700 text-rose-200 text-xs">
            Retry Connection
          </Button>
        </Card>
      )}

      {/* Loading State */}
      {loading && !error && (
        <div className="space-y-6">
          {[1, 2].map((i) => (
            <Card key={i} className="bg-slate-900/60 border-slate-800 p-6 animate-pulse space-y-4">
              <div className="flex justify-between items-center">
                <div className="h-5 bg-slate-800 rounded w-1/3" />
                <div className="h-4 bg-slate-800 rounded w-1/6" />
              </div>
              <div className="h-4 bg-slate-700/60 rounded w-2/3" />
              <div className="h-16 bg-slate-800/40 rounded w-full" />
            </Card>
          ))}
        </div>
      )}

      {/* Empty State */}
      {!loading && !error && filteredWorkflows.length === 0 && (
        <Card className="bg-slate-900/60 border-slate-800 py-16 px-6 text-center shadow-xl">
          <CardContent className="space-y-4 max-w-sm mx-auto">
            <div className="h-12 w-12 rounded-xl bg-purple-500/15 text-purple-400 flex items-center justify-center mx-auto">
              <GitFork className="h-6 w-6" />
            </div>
            <h3 className="text-base font-bold text-white">No Workflows Configured</h3>
            <p className="text-xs text-slate-400">
              Create your first workflow to automate task assignment, document actions, or status updates.
            </p>
            <Button onClick={handleOpenCreate} size="sm" className="bg-purple-600 hover:bg-purple-500 text-xs text-white">
              <Plus className="h-4 w-4 mr-1" />
              Create Workflow
            </Button>
          </CardContent>
        </Card>
      )}

      {/* Workflow List */}
      {!loading && !error && filteredWorkflows.length > 0 && (
        <div className="space-y-6">
          {filteredWorkflows.map((wf) => {
            const triggerInfo = TRIGGER_LABELS[wf.trigger?.type] || TRIGGER_LABELS.manual;
            return (
              <Card
                key={wf._id}
                className="bg-slate-900/80 border-slate-800 shadow-xl hover:border-slate-700 transition-all group overflow-hidden"
              >
                <CardHeader className="pb-3 border-b border-slate-800/80">
                  <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-3">
                    <div className="space-y-1">
                      <div className="flex items-center space-x-2 flex-wrap gap-y-1">
                        <CardTitle className="text-lg font-bold text-white group-hover:text-purple-300 transition-colors">
                          {wf.name}
                        </CardTitle>
                        <span className={`text-[10px] font-semibold px-2 py-0.5 rounded-full capitalize ${
                          wf.status === 'active' ? 'bg-emerald-500/15 text-emerald-400 border border-emerald-500/30' :
                          'bg-slate-700/40 text-slate-300 border border-slate-600/30'
                        }`}>
                          {wf.status}
                        </span>
                        <Badge variant="outline" className={`text-[10px] ${triggerInfo.color}`}>
                          {triggerInfo.label}
                        </Badge>
                      </div>
                      <CardDescription className="text-slate-400 text-xs">
                        {wf.description || 'No description provided.'}
                      </CardDescription>
                    </div>

                    {/* Action Buttons */}
                    <div className="flex items-center space-x-2">
                      <Button
                        size="sm"
                        onClick={() => handleRunWorkflow(wf)}
                        className="bg-emerald-600 hover:bg-emerald-500 text-white text-xs px-3 h-8 shadow-sm"
                        title="Run Workflow Now"
                      >
                        <Play className="h-3 w-3 mr-1 fill-current" />
                        Run
                      </Button>
                      <Button
                        size="sm"
                        variant="outline"
                        onClick={() => handleOpenHistory(wf)}
                        className="border-slate-700 bg-slate-800/60 hover:bg-slate-700 text-slate-300 text-xs px-3 h-8"
                        title="Execution History"
                      >
                        <History className="h-3 w-3 mr-1" />
                        History ({wf.executionStats?.totalRuns || 0})
                      </Button>
                      <Button
                        size="sm"
                        variant="outline"
                        onClick={() => handleToggleActive(wf)}
                        className={`text-xs px-2.5 h-8 border-slate-700 ${
                          wf.status === 'active' ? 'text-amber-400 hover:bg-amber-950/20' : 'text-emerald-400 hover:bg-emerald-950/20'
                        }`}
                        title={wf.status === 'active' ? 'Deactivate' : 'Activate'}
                      >
                        <Power className="h-3.5 w-3.5" />
                      </Button>
                      <Button
                        size="sm"
                        variant="outline"
                        onClick={() => handleOpenEdit(wf)}
                        className="border-slate-700 bg-slate-800/60 hover:bg-slate-700 text-slate-300 text-xs px-2.5 h-8"
                        title="Edit Workflow"
                      >
                        <Edit className="h-3.5 w-3.5" />
                      </Button>
                      <Button
                        size="sm"
                        variant="outline"
                        onClick={() => handleDeleteWorkflow(wf._id, wf.name)}
                        className="border-slate-700 bg-slate-800/60 hover:bg-rose-950/40 text-rose-400 text-xs px-2.5 h-8"
                        title="Delete Workflow"
                      >
                        <Trash2 className="h-3.5 w-3.5" />
                      </Button>
                    </div>
                  </div>
                </CardHeader>

                <CardContent className="pt-4">
                  <div className="flex items-center justify-between mb-3">
                    <div className="text-xs font-semibold text-slate-400 uppercase tracking-wider">
                      Ordered Execution Steps ({wf.steps?.length || 0})
                    </div>
                    {wf.executionStats?.lastRunAt && (
                      <span className="text-[11px] text-slate-500 flex items-center">
                        <Clock className="h-3 w-3 mr-1" />
                        Last run: {new Date(wf.executionStats.lastRunAt).toLocaleDateString()} {new Date(wf.executionStats.lastRunAt).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}
                      </span>
                    )}
                  </div>

                  {wf.steps && wf.steps.length > 0 ? (
                    <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-3">
                      {wf.steps.map((step) => {
                        const stepMeta = STEP_TYPE_OPTIONS.find(s => s.value === step.stepType) || { label: step.stepType, icon: Settings2 };
                        const StepIcon = stepMeta.icon;
                        return (
                          <div
                            key={step._id || step.stepOrder}
                            className="p-3.5 rounded-xl bg-slate-950/60 border border-slate-800/80 flex flex-col justify-between space-y-2 hover:border-slate-700/80 transition-colors"
                          >
                            <div className="flex items-center justify-between">
                              <span className="text-[10px] font-mono font-bold px-1.5 py-0.5 rounded bg-purple-500/15 text-purple-300 border border-purple-500/30">
                                #{step.stepOrder}
                              </span>
                              <span className={`text-[9px] font-medium px-1.5 py-0.5 rounded ${
                                step.onFailure === 'continue' ? 'bg-amber-500/10 text-amber-300' : 'bg-slate-800 text-slate-400'
                              }`}>
                                On failure: {step.onFailure || 'stop'}
                              </span>
                            </div>

                            <div className="flex items-center space-x-2">
                              <StepIcon className="h-4 w-4 text-purple-400 shrink-0" />
                              <div className="text-xs font-semibold text-slate-200 truncate">
                                {step.stepName}
                              </div>
                            </div>

                            <div className="text-[11px] text-slate-400 font-mono truncate bg-slate-900/60 px-2 py-1 rounded">
                              {stepMeta.label}
                            </div>
                          </div>
                        );
                      })}
                    </div>
                  ) : (
                    <div className="p-4 rounded-xl bg-slate-950/40 border border-slate-800/60 text-xs text-slate-500">
                      No steps configured. Click Edit to add steps to this pipeline.
                    </div>
                  )}
                </CardContent>
              </Card>
            );
          })}
        </div>
      )}

      {/* WORKFLOW BUILDER MODAL */}
      {isBuilderOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/75 backdrop-blur-sm overflow-y-auto">
          <div className="bg-slate-900 border border-slate-800 rounded-2xl w-full max-w-3xl max-h-[90vh] flex flex-col shadow-2xl overflow-hidden my-8">
            {/* Modal Header */}
            <div className="px-6 py-4 border-b border-slate-800 flex items-center justify-between bg-slate-900/90">
              <div className="flex items-center space-x-2">
                <div className="h-8 w-8 rounded-lg bg-purple-500/15 text-purple-400 flex items-center justify-center">
                  <GitFork className="h-4 w-4" />
                </div>
                <div>
                  <h2 className="text-lg font-bold text-white">
                    {editingWorkflow ? 'Edit Workflow Pipeline' : 'Create New Workflow'}
                  </h2>
                  <p className="text-xs text-slate-400">Configure trigger and ordered execution steps</p>
                </div>
              </div>
              <button
                onClick={() => setIsBuilderOpen(false)}
                className="text-slate-400 hover:text-white p-1 rounded-lg"
              >
                ✕
              </button>
            </div>

            {/* Modal Body */}
            <form onSubmit={handleSaveWorkflow} className="flex-1 overflow-y-auto p-6 space-y-6">
              {builderError && (
                <div className="p-3 rounded-xl bg-rose-950/40 border border-rose-800 text-rose-200 text-xs">
                  {builderError}
                </div>
              )}

              {/* General Settings */}
              <div className="space-y-4 bg-slate-950/40 p-4 rounded-xl border border-slate-800/80">
                <h3 className="text-xs font-bold text-purple-400 uppercase tracking-wider">1. General Information</h3>
                <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
                  <div>
                    <label className="block text-xs font-medium text-slate-300 mb-1">Workflow Name *</label>
                    <input
                      type="text"
                      required
                      value={builderForm.name}
                      onChange={(e) => setBuilderForm({ ...builderForm, name: e.target.value })}
                      placeholder="e.g. Sprint Review Auto-Tasks"
                      className="w-full px-3 py-2 bg-slate-900 border border-slate-700 rounded-lg text-xs text-white focus:outline-none focus:border-purple-500"
                    />
                  </div>
                  <div>
                    <label className="block text-xs font-medium text-slate-300 mb-1">Status</label>
                    <select
                      value={builderForm.status}
                      onChange={(e) => setBuilderForm({ ...builderForm, status: e.target.value })}
                      className="w-full px-3 py-2 bg-slate-900 border border-slate-700 rounded-lg text-xs text-slate-200 focus:outline-none focus:border-purple-500"
                    >
                      <option value="active">Active (Eligible to execute)</option>
                      <option value="draft">Draft (Inactive)</option>
                      <option value="paused">Paused</option>
                    </select>
                  </div>
                </div>
                <div>
                  <label className="block text-xs font-medium text-slate-300 mb-1">Description</label>
                  <textarea
                    rows={2}
                    value={builderForm.description}
                    onChange={(e) => setBuilderForm({ ...builderForm, description: e.target.value })}
                    placeholder="Describe what this workflow automates..."
                    className="w-full px-3 py-2 bg-slate-900 border border-slate-700 rounded-lg text-xs text-white focus:outline-none focus:border-purple-500"
                  />
                </div>
              </div>

              {/* Trigger Settings */}
              <div className="space-y-4 bg-slate-950/40 p-4 rounded-xl border border-slate-800/80">
                <h3 className="text-xs font-bold text-blue-400 uppercase tracking-wider">2. Trigger Configuration</h3>
                <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
                  <div>
                    <label className="block text-xs font-medium text-slate-300 mb-1">Trigger Event</label>
                    <select
                      value={builderForm.trigger.type}
                      onChange={(e) => setBuilderForm({
                        ...builderForm,
                        trigger: { ...builderForm.trigger, type: e.target.value }
                      })}
                      className="w-full px-3 py-2 bg-slate-900 border border-slate-700 rounded-lg text-xs text-slate-200 focus:outline-none focus:border-purple-500"
                    >
                      <option value="manual">Manual (Run Button)</option>
                      <option value="task_created">Task Created (Event-Driven)</option>
                      <option value="task_completed">Task Completed (Event-Driven)</option>
                      <option value="document_uploaded">Document Uploaded (Event-Driven)</option>
                      <option value="scheduled">Scheduled Timer (In-App Scheduler)</option>
                    </select>
                  </div>

                  {builderForm.trigger.type === 'scheduled' && (
                    <div>
                      <label className="block text-xs font-medium text-slate-300 mb-1">Interval (Minutes)</label>
                      <input
                        type="number"
                        min="1"
                        max="1440"
                        value={builderForm.trigger.config?.intervalMinutes || 60}
                        onChange={(e) => setBuilderForm({
                          ...builderForm,
                          trigger: {
                            ...builderForm.trigger,
                            config: { ...builderForm.trigger.config, intervalMinutes: parseInt(e.target.value, 10) || 60 }
                          }
                        })}
                        className="w-full px-3 py-2 bg-slate-900 border border-slate-700 rounded-lg text-xs text-white focus:outline-none focus:border-purple-500"
                      />
                    </div>
                  )}
                </div>
              </div>

              {/* Ordered Steps Settings */}
              <div className="space-y-4 bg-slate-950/40 p-4 rounded-xl border border-slate-800/80">
                <div className="flex items-center justify-between">
                  <h3 className="text-xs font-bold text-emerald-400 uppercase tracking-wider">3. Ordered Execution Steps</h3>
                  <Button
                    type="button"
                    size="sm"
                    variant="outline"
                    onClick={handleAddStep}
                    className="border-emerald-600/40 text-emerald-300 hover:bg-emerald-950/20 text-xs h-7 px-2.5"
                  >
                    <Plus className="h-3.5 w-3.5 mr-1" />
                    Add Step
                  </Button>
                </div>

                {builderForm.steps.length === 0 ? (
                  <div className="p-4 rounded-xl bg-slate-900/60 border border-slate-800 text-xs text-slate-400 text-center">
                    No steps added. Click "Add Step" to configure action pipeline.
                  </div>
                ) : (
                  <div className="space-y-4">
                    {builderForm.steps.map((step, idx) => (
                      <div key={idx} className="p-4 rounded-xl bg-slate-900 border border-slate-800 space-y-3 relative">
                        <div className="flex items-center justify-between">
                          <span className="text-[10px] font-mono font-bold px-2 py-0.5 rounded bg-purple-500/20 text-purple-300">
                            Step #{step.stepOrder}
                          </span>
                          <button
                            type="button"
                            onClick={() => handleRemoveStep(idx)}
                            className="text-slate-500 hover:text-rose-400 text-xs"
                          >
                            Remove
                          </button>
                        </div>

                        <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
                          <div className="sm:col-span-2">
                            <label className="block text-[11px] font-medium text-slate-400 mb-1">Step Name</label>
                            <input
                              type="text"
                              required
                              value={step.stepName}
                              onChange={(e) => handleUpdateStep(idx, 'stepName', e.target.value)}
                              placeholder="Step title"
                              className="w-full px-2.5 py-1.5 bg-slate-950 border border-slate-700 rounded-lg text-xs text-white focus:outline-none focus:border-purple-500"
                            />
                          </div>
                          <div>
                            <label className="block text-[11px] font-medium text-slate-400 mb-1">Action Type</label>
                            <select
                              value={step.stepType}
                              onChange={(e) => handleUpdateStep(idx, 'stepType', e.target.value)}
                              className="w-full px-2.5 py-1.5 bg-slate-950 border border-slate-700 rounded-lg text-xs text-slate-200 focus:outline-none focus:border-purple-500"
                            >
                              {STEP_TYPE_OPTIONS.map(opt => (
                                <option key={opt.value} value={opt.value}>{opt.label}</option>
                              ))}
                            </select>
                          </div>
                        </div>

                        {/* Step Specific Action Config */}
                        {step.stepType === 'create_task' && (
                          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 pt-2 border-t border-slate-800">
                            <div>
                              <label className="block text-[11px] font-medium text-slate-400 mb-1">Task Title</label>
                              <input
                                type="text"
                                value={step.config?.title || ''}
                                onChange={(e) => handleUpdateStepConfig(idx, 'title', e.target.value)}
                                placeholder="Automated Task Title"
                                className="w-full px-2.5 py-1.5 bg-slate-950 border border-slate-700 rounded-lg text-xs text-white"
                              />
                            </div>
                            <div>
                              <label className="block text-[11px] font-medium text-slate-400 mb-1">Priority</label>
                              <select
                                value={step.config?.priority || 'medium'}
                                onChange={(e) => handleUpdateStepConfig(idx, 'priority', e.target.value)}
                                className="w-full px-2.5 py-1.5 bg-slate-950 border border-slate-700 rounded-lg text-xs text-slate-200"
                              >
                                <option value="low">Low</option>
                                <option value="medium">Medium</option>
                                <option value="high">High</option>
                                <option value="urgent">Urgent</option>
                              </select>
                            </div>
                          </div>
                        )}

                        {step.stepType === 'update_task_status' && (
                          <div className="pt-2 border-t border-slate-800">
                            <label className="block text-[11px] font-medium text-slate-400 mb-1">Target Status</label>
                            <select
                              value={step.config?.status || 'completed'}
                              onChange={(e) => handleUpdateStepConfig(idx, 'status', e.target.value)}
                              className="w-full px-2.5 py-1.5 bg-slate-950 border border-slate-700 rounded-lg text-xs text-slate-200"
                            >
                              <option value="todo">To Do</option>
                              <option value="in-progress">In Progress</option>
                              <option value="completed">Completed</option>
                            </select>
                          </div>
                        )}

                        <div className="flex items-center justify-between pt-1">
                          <label className="text-[11px] text-slate-400 flex items-center space-x-1.5">
                            <span>Failure Policy:</span>
                            <select
                              value={step.onFailure || 'stop'}
                              onChange={(e) => handleUpdateStep(idx, 'onFailure', e.target.value)}
                              className="bg-slate-950 border border-slate-800 rounded px-2 py-0.5 text-[10px] text-slate-300"
                            >
                              <option value="stop">Stop Workflow on Failure</option>
                              <option value="continue">Continue to Next Step</option>
                            </select>
                          </label>
                        </div>
                      </div>
                    ))}
                  </div>
                )}
              </div>

              {/* Submit Buttons */}
              <div className="flex items-center justify-end space-x-3 pt-4 border-t border-slate-800">
                <Button
                  type="button"
                  variant="outline"
                  onClick={() => setIsBuilderOpen(false)}
                  className="border-slate-700 text-slate-300 text-xs"
                >
                  Cancel
                </Button>
                <Button
                  type="submit"
                  disabled={savingWorkflow}
                  className="bg-purple-600 hover:bg-purple-500 text-white text-xs font-semibold px-4"
                >
                  {savingWorkflow ? 'Saving...' : editingWorkflow ? 'Update Workflow' : 'Create Workflow'}
                </Button>
              </div>
            </form>
          </div>
        </div>
      )}

      {/* EXECUTION HISTORY MODAL */}
      {historyModal.isOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/75 backdrop-blur-sm overflow-y-auto">
          <div className="bg-slate-900 border border-slate-800 rounded-2xl w-full max-w-3xl max-h-[90vh] flex flex-col shadow-2xl overflow-hidden my-8">
            <div className="px-6 py-4 border-b border-slate-800 flex items-center justify-between bg-slate-900/90">
              <div className="flex items-center space-x-2">
                <div className="h-8 w-8 rounded-lg bg-blue-500/15 text-blue-400 flex items-center justify-center">
                  <History className="h-4 w-4" />
                </div>
                <div>
                  <h2 className="text-lg font-bold text-white">Execution Logs</h2>
                  <p className="text-xs text-slate-400">{historyModal.workflow?.name}</p>
                </div>
              </div>
              <button
                onClick={() => setHistoryModal({ ...historyModal, isOpen: false })}
                className="text-slate-400 hover:text-white p-1 rounded-lg"
              >
                ✕
              </button>
            </div>

            <div className="flex-1 overflow-y-auto p-6 space-y-4">
              {historyModal.loading && (
                <div className="py-12 text-center text-xs text-slate-400">Loading executions...</div>
              )}

              {historyModal.error && (
                <div className="p-4 rounded-xl bg-rose-950/40 border border-rose-800 text-rose-200 text-xs">
                  {historyModal.error}
                </div>
              )}

              {!historyModal.loading && !historyModal.error && historyModal.executions.length === 0 && (
                <div className="py-12 text-center space-y-2">
                  <div className="text-slate-400 text-xs">No execution history recorded yet.</div>
                  <Button
                    size="sm"
                    onClick={() => handleRunWorkflow(historyModal.workflow)}
                    className="bg-emerald-600 hover:bg-emerald-500 text-white text-xs"
                  >
                    <Play className="h-3 w-3 mr-1 fill-current" />
                    Trigger First Run
                  </Button>
                </div>
              )}

              {!historyModal.loading && !historyModal.error && historyModal.executions.length > 0 && (
                <div className="space-y-4">
                  {historyModal.executions.map((exec) => (
                    <div
                      key={exec._id}
                      className="p-4 rounded-xl bg-slate-950 border border-slate-800 space-y-3"
                    >
                      <div className="flex items-center justify-between flex-wrap gap-2">
                        <div className="flex items-center space-x-2">
                          <span className={`text-[10px] font-bold px-2 py-0.5 rounded-full uppercase ${
                            exec.status === 'completed' ? 'bg-emerald-500/20 text-emerald-400 border border-emerald-500/40' :
                            exec.status === 'failed' ? 'bg-rose-500/20 text-rose-400 border border-rose-500/40' :
                            'bg-blue-500/20 text-blue-400 border border-blue-500/40'
                          }`}>
                            {exec.status}
                          </span>
                          <span className="text-xs text-slate-300 font-mono">
                            Trigger: {exec.triggerType}
                          </span>
                        </div>
                        <div className="text-[11px] text-slate-400 flex items-center space-x-3">
                          <span>Duration: {exec.durationMs ? `${exec.durationMs}ms` : 'N/A'}</span>
                          <span>{new Date(exec.startedAt || exec.createdAt).toLocaleString()}</span>
                        </div>
                      </div>

                      {exec.errorMessage && (
                        <div className="p-2.5 rounded bg-rose-950/30 border border-rose-900/60 text-rose-300 text-xs">
                          {exec.errorMessage}
                        </div>
                      )}

                      {/* Step Execution Details */}
                      {exec.stepResults && exec.stepResults.length > 0 && (
                        <div className="space-y-1.5 pt-2 border-t border-slate-900">
                          <div className="text-[10px] font-bold uppercase tracking-wider text-slate-500">Step Results</div>
                          <div className="grid grid-cols-1 sm:grid-cols-2 gap-2">
                            {exec.stepResults.map((sr, sIdx) => (
                              <div key={sIdx} className="p-2 rounded bg-slate-900/80 border border-slate-800/80 text-[11px] flex items-center justify-between">
                                <span className="text-slate-300 truncate mr-2">
                                  #{sr.stepOrder} {sr.stepName || sr.stepType}
                                </span>
                                <span className={`text-[10px] font-medium ${
                                  sr.status === 'completed' ? 'text-emerald-400' : 'text-rose-400'
                                }`}>
                                  {sr.status}
                                </span>
                              </div>
                            ))}
                          </div>
                        </div>
                      )}

                      {/* Created Task Links */}
                      {exec.createdTasks && exec.createdTasks.length > 0 && (
                        <div className="pt-2 text-[11px] text-slate-400 flex items-center space-x-2">
                          <CheckCircle2 className="h-3.5 w-3.5 text-emerald-400" />
                          <span>Generated {exec.createdTasks.length} task(s) in MongoDB backlog</span>
                        </div>
                      )}
                    </div>
                  ))}
                </div>
              )}
            </div>
          </div>
        </div>
      )}
    </div>
  );
}

export default Workflows;
